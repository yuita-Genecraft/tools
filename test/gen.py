n = 0
def U():
    global n
    n += 1
    return f"00000000-0000-4000-8000-{n:012d}"

def user(text=None, blocks=None, ts="", sid="s1", cwd="/Users/t/dev/alpha", **kw):
    o = {"parentUuid": None, "isSidechain": False, "userType": "external", "cwd": cwd, "sessionId": sid,
         "version": "2.1.0", "gitBranch": "main", "type": "user",
         "message": {"role": "user", "content": text if text is not None else blocks},
         "uuid": U(), "timestamp": ts}
    o.update(kw)
    return o

def asst(block, mid, rid, model, usage, ts="", sid="s1", cwd="/Users/t/dev/alpha", **kw):
    o = {"parentUuid": None, "isSidechain": False, "userType": "external", "cwd": cwd, "sessionId": sid,
         "version": "2.1.0", "type": "assistant", "requestId": rid,
         "message": {"id": mid, "type": "message", "role": "assistant", "model": model,
                     "content": [block], "stop_reason": None, "usage": usage},
         "uuid": U(), "timestamp": ts}
    o.update(kw)
    return o

def usage(i, o, cw=0, cr=0, c5=None, c1=None):
    u = {"input_tokens": i, "output_tokens": o, "cache_creation_input_tokens": cw, "cache_read_input_tokens": cr}
    if c5 is not None or c1 is not None:
        u["cache_creation"] = {"ephemeral_5m_input_tokens": c5 or 0, "ephemeral_1h_input_tokens": c1 or 0}
    return u

